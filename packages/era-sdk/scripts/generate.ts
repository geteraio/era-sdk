/**
 * Generates src/generated.ts from Era's OpenAPI document (R52 C1).
 *
 *   bun run scripts/generate.ts                      # from the kernel in this repo (same function the API serves)
 *   bun run scripts/generate.ts --from <url>         # from a running Era: <origin>/api/v1/openapi.json
 *
 * Output: a type per data model, a type per action input, the action-name map
 * for `era.actions.run`, and the resource table `createEra` builds methods from.
 * Re-run it whenever a module manifest changes; `bun run check` fails when the
 * committed file is stale.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const OUT = join(here, '..', 'src', 'generated.ts')
const checkOnly = process.argv.includes('--check')
const fromIdx = process.argv.indexOf('--from')

type Obj = Record<string, any>

async function loadDoc(): Promise<Obj> {
  if (fromIdx > 0) {
    const res = await fetch(process.argv[fromIdx + 1]!)
    if (!res.ok) throw new Error(`GET ${process.argv[fromIdx + 1]} → ${res.status}`)
    return (await res.json()) as Obj
  }
  const kernel = await import(pathToFileURL(join(here, '../../os-kernel/src/platform-api/index.ts')).href)
  return kernel.eraOpenApi('https://app.getera.io') as Obj
}

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/
const key = (k: string) => (IDENT.test(k) ? k : JSON.stringify(k))
const camel = (s: string) => s.replace(/[_.-](\w)/g, (_, c: string) => c.toUpperCase())
const doc = (text: unknown, indent = '  ') =>
  typeof text === 'string' && text.trim() ? `${indent}/** ${text.replace(/\*\//g, '* /').replace(/\s+/g, ' ').trim()} */\n` : ''

function tsType(s: Obj | undefined): string {
  if (!s) return 'unknown'
  if (s.$ref) return String(s.$ref).split('/').pop()!
  if (Array.isArray(s.enum)) return s.enum.map((v: unknown) => (v === null ? 'null' : JSON.stringify(v))).join(' | ')
  const types: string[] = Array.isArray(s.type) ? s.type : s.type ? [s.type] : []
  if (!types.length) return 'unknown'
  if (types.includes('object') && types.includes('array')) return types.includes('null') ? 'unknown' : 'unknown'
  return types
    .map((t) => {
      switch (t) {
        case 'string':
          return 'string'
        case 'integer':
        case 'number':
          return 'number'
        case 'boolean':
          return 'boolean'
        case 'null':
          return 'null'
        case 'array':
          return `${tsType(s.items) === 'unknown' ? 'unknown' : tsType(s.items)}[]`
        case 'object':
          return 'Record<string, unknown>'
        default:
          return 'unknown'
      }
    })
    .join(' | ')
}

function iface(name: string, schema: Obj, opts: { optionalAll?: boolean; omit?: string[] } = {}): string {
  const required = new Set<string>(schema.required ?? [])
  const lines = Object.entries<Obj>(schema.properties ?? {})
    .filter(([k]) => !opts.omit?.includes(k))
    .map(([k, s]) => `${doc(s.description ?? s.title)}  ${key(k)}${!opts.optionalAll && required.has(k) ? '' : '?'}: ${tsType(s)}`)
  return `${doc(schema.description ?? schema.title, '')}export interface ${name} {\n${lines.join('\n')}\n}\n`
}

const RESERVED = new Set(['list', 'listAll', 'get', 'create', 'update', 'delete'])

async function main() {
  const api = await loadDoc()
  const schemas: Obj = api.components.schemas
  const out: string[] = [
    '/* eslint-disable */',
    `// Generated by scripts/generate.ts from the Era OpenAPI document (API version ${api.info.version}). Do not edit.`,
    "import type { ActionResult, CallOptions, ListParams, ListPage } from './client'",
    '',
    `export const API_VERSION = ${JSON.stringify(api.info.version)}`,
    '',
    '// ── data models ──',
  ]

  // Models: every schema that is not an action input or a wrapper.
  const models = Object.keys(schemas).filter((n) => !n.endsWith('Input') && n !== 'Error' && n !== 'ActionResult').sort()
  for (const n of models) out.push(iface(n, schemas[n]))

  // Actions: every POST operation that names an action.
  const actions = new Map<string, { input: string; path: string; summary: string; requires: string; preconditions: Obj[]; idField?: string }>()
  const resources = new Map<string, { model?: string; create?: string; update?: string; remove?: string; methods: Map<string, { action: string; kind: 'i' | 'c'; verb: string }> }>()
  for (const [path, item] of Object.entries<Obj>(api.paths)) {
    const m = /^\/api\/v1\/([a-z0-9_]+)(\/\{id\})?(?:\/actions\/([a-z0-9_]+))?$/.exec(path)
    for (const [method, op] of Object.entries<Obj>(item)) {
      if (method === 'parameters') continue
      const action: string | undefined = op['x-era-action']
      if (action && !actions.has(action)) {
        const ref: string | undefined = op.requestBody?.content?.['application/json']?.schema?.$ref
        actions.set(action, {
          input: ref ? ref.split('/').pop()! : 'Record<string, unknown>',
          path: op['x-era-canonical-path'] ?? path,
          summary: `${op.summary}${op.description ? ` — ${op.description}` : ''}`,
          requires: op['x-era-requires'],
          preconditions: op['x-era-preconditions'] ?? [],
          idField: op['x-era-id-field'],
        })
      }
      if (!m || m[1] === 'actions' || m[1] === 'me' || !op['x-era-resource'] && !action) continue
      const name = m[1]!
      const r = resources.get(name) ?? { methods: new Map() }
      resources.set(name, r)
      if (method === 'get' && !m[2]) {
        const items = op.responses?.['200']?.content?.['application/json']?.schema?.properties?.data?.items?.$ref
        if (items) r.model = String(items).split('/').pop()
      }
      if (!action) continue
      if (m[3]) {
        let fn = camel(m[3])
        if (RESERVED.has(fn) && !(fn === 'create' || fn === 'update' || fn === 'delete')) fn = `${fn}Action`
        r.methods.set(fn, { action, kind: m[2] ? 'i' : 'c', verb: m[3] })
      } else if (method === 'post') r.create = action
      else if (method === 'patch') r.update = action
      else if (method === 'delete') r.remove = action
    }
  }

  out.push('// ── action inputs ──')
  for (const n of Object.keys(schemas).filter((n) => n.endsWith('Input')).sort()) out.push(iface(n, schemas[n]))

  out.push('/** Every action, by name — `era.actions.run(name, input)` is typed by this map. */')
  out.push('export interface ActionInputs {')
  for (const [name, a] of [...actions].sort(([x], [y]) => x.localeCompare(y))) {
    const pre = a.preconditions.length ? ` Refuses with: ${a.preconditions.map((p) => p.code).join(', ')}.` : ''
    out.push(`${doc(`${a.summary} Needs ${a.requires}.${pre}`)}  ${JSON.stringify(name)}: ${a.input}`)
  }
  out.push('}\nexport type ActionName = keyof ActionInputs\n')

  // Resource types + the runtime table.
  const table: string[] = []
  const types: string[] = []
  const props: string[] = []
  for (const [name, r] of [...resources].sort(([a], [b]) => a.localeCompare(b))) {
    const model = r.model ?? 'Record<string, unknown>'
    const T = `${camel(`_${name}`)}Resource`
    const lines: string[] = [
      `  /** One page of ${name}, newest first. Filter by any column: \`{ status: 'paid' }\`, \`{ 'created_at[gte]': '2026-01-01' }\`. */`,
      `  list(params?: ListParams & Partial<Record<keyof ${model} | \`\${string}[\${string}]\`, string | number | boolean | null>>, opts?: CallOptions): Promise<ListPage<${model}>>`,
      `  /** Every row, page by page. */`,
      `  listAll(params?: Omit<ListParams, 'cursor'> & Partial<Record<keyof ${model} | \`\${string}[\${string}]\`, string | number | boolean | null>>): AsyncGenerator<${model}>`,
      `  get(id: string, opts?: CallOptions): Promise<${model}>`,
    ]
    const omitId = (action: string) => {
      const a = actions.get(action)!
      return a.idField ? `Omit<${a.input}, ${JSON.stringify(a.idField)}>` : a.input
    }
    if (r.create) lines.push(`  /** Runs ${r.create}. */\n  create(input: ${actions.get(r.create)!.input}, opts?: CallOptions): Promise<ActionResult>`)
    if (r.update) lines.push(`  /** Runs ${r.update}. */\n  update(id: string, input: Partial<${omitId(r.update)}>, opts?: CallOptions): Promise<ActionResult>`)
    if (r.remove) lines.push(`  /** Runs ${r.remove}. */\n  delete(id: string, opts?: CallOptions): Promise<ActionResult>`)
    const tm: string[] = []
    for (const [fn, m] of [...r.methods].sort(([a], [b]) => a.localeCompare(b))) {
      if ((fn === 'create' && r.create) || (fn === 'update' && r.update) || (fn === 'delete' && r.remove)) continue
      const a = actions.get(m.action)!
      lines.push(doc(`${a.summary} (${m.action})`) + (m.kind === 'i'
        ? `  ${key(fn)}(id: string, input?: Partial<${omitId(m.action)}>, opts?: CallOptions): Promise<ActionResult>`
        : `  ${key(fn)}(input: ${a.input}, opts?: CallOptions): Promise<ActionResult>`))
      tm.push(`${key(fn)}: [${JSON.stringify(m.verb)}, ${JSON.stringify(m.kind)}]`)
    }
    types.push(`export interface ${T} {\n${lines.join('\n')}\n}`)
    props.push(`  ${key(camel(name))}: ${T}`)
    table.push(`  ${key(name)}: { c: ${r.create ? 1 : 0}, u: ${r.update ? 1 : 0}, d: ${r.remove ? 1 : 0}, a: { ${tm.join(', ')} } },`)
  }
  out.push('// ── resources ──')
  out.push(types.join('\n\n'))
  out.push(`\nexport interface EraResources {\n${props.join('\n')}\n}\n`)
  out.push('/** The runtime table createEra builds methods from: c/u/d = create/update/delete aliases, a = actions ([verb, i=on a record | c=on the collection]). */')
  out.push(`export const RESOURCES: Record<string, { c: number; u: number; d: number; a: Record<string, [string, 'i' | 'c']> }> = {\n${table.join('\n')}\n}\n`)

  const text = `${out.join('\n')}\n`
  if (checkOnly) {
    const current = readFileSync(OUT, 'utf8')
    if (current !== text) {
      console.error('src/generated.ts is stale — run: bun run generate')
      process.exit(1)
    }
    console.log('src/generated.ts is current.')
    return
  }
  writeFileSync(OUT, text, 'utf8')
  console.log(`wrote src/generated.ts: ${models.length} models, ${actions.size} actions, ${resources.size} resources (${(text.length / 1024).toFixed(0)} KB)`)
}

await main()
