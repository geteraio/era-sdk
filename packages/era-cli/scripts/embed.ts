/**
 * Builds the two files an Era chat's terminal gets on the desktop and embeds them as strings, so the
 * Station server (which bundles this package's sources) can write them without any repo path:
 *
 *   ERA_PUBLIC_CLI_JS   the public CLI (src/public/entry.ts) → `<work folder>/.era/bin/era-public.mjs`
 *   ERA_SDK_BROWSER_JS  @getera/sdk as one classic script   → `<work folder>/.era/lib/era-sdk.js`
 *   ERA_SITE_BROWSER_JS @getera/storefront as one classic script (content binding, cart, posts) → `.era/lib/era-site.js`
 *
 *   bun run embed      (writes src/embedded.generated.ts; `--check` fails when it is stale)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sdk = join(root, "..", "era-sdk", "src", "browser.ts");
const storefront = join(root, "..", "era-storefront", "src", "site.ts");

async function one(entry: string, target: "node" | "browser", format: "esm" | "iife"): Promise<string> {
  const out = await Bun.build({ entrypoints: [entry], target, format, minify: true });
  if (!out.success) {
    for (const log of out.logs) console.error(log);
    process.exit(1);
  }
  return (await out.outputs[0]!.text()).replace(/^#!.*\n/, "");
}

const cli = await one(join(root, "src", "public", "entry.ts"), "node", "esm");
const browser = await one(sdk, "browser", "iife");
const site = await one(storefront, "browser", "iife");
const file = join(root, "src", "embedded.generated.ts");
const text = `// Generated by scripts/embed.ts — do not edit. Rebuild with: cd packages/era-cli && bun run embed\n/* eslint-disable */\nexport const ERA_PUBLIC_CLI_JS: string = ${JSON.stringify(`#!/usr/bin/env node\n// Era writes this file. No credentials are stored here.\n${cli}`)};\nexport const ERA_SDK_BROWSER_JS: string = ${JSON.stringify(`/* @getera/sdk — Era writes this file. window.EraSDK; no credentials inside. */\n${browser}`)};\nexport const ERA_SITE_BROWSER_JS: string = ${JSON.stringify(`/* @getera/storefront era-site.js — Era writes this file. Binds the owner's Era content, cart, checkout and posts; the site id is a publishable key. */\n${site}`)};\n`;
if (process.argv.includes("--check")) {
  const current = (() => { try { return readFileSync(file, "utf8"); } catch { return ""; } })();
  if (current !== text) {
    console.error("src/embedded.generated.ts is stale: run bun run embed");
    process.exit(1);
  }
  console.log("embedded.generated.ts is current");
} else {
  writeFileSync(file, text);
  console.log(`embedded: public CLI ${(cli.length / 1024).toFixed(0)} KB, SDK browser ${(browser.length / 1024).toFixed(0)} KB, era-site.js ${(site.length / 1024).toFixed(0)} KB`);
}
